"""黄金向量生成 —— 用 Python golden model 生成总线帧序列参照文件。

场景 = tb_servo_bus.sv 的验证序列（复位→时隙下发→轮询回读→掉线→事件帧）。
产物 ``fpga/sim/golden_vectors.txt``：每行一个字节事件 ``<dir> <hex>``，
dir: M=主机→总线（scs_protocol_tx 输出），S=从机→主机（scs_slave_model 响应）。
队友的 xsim TB 可 `$fscanf` 逐行驱动/断言，无需理解 Python。

运行::

    python tools/dump_golden_vectors.py
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "host"))

from app.control import scs_protocol as sp  # noqa: E402
from app.control import scs_sim  # noqa: E402

OUT = REPO_ROOT / "fpga/sim/golden_vectors.txt"


def main() -> int:
    bus = scs_sim.VirtualServoBus()
    lines: list[str] = []

    def req(frame: bytes, note: str) -> None:
        lines.append(f"# {note}")
        for b in frame:
            lines.append(f"M {b:02X}")
        resp = bus.transact(frame)
        if resp is not None:
            for b in resp:
                lines.append(f"S {b:02X}")

    lines.append("# golden vectors — generated by tools/dump_golden_vectors.py")
    lines.append("# scenario: sync_write(pos=2040) x1, read #1..#3 w/ load, bc_speed, drop #4")

    # 1. 时隙下发：全舵机目标 2040（0x7F8）
    req(sp.build_sync_write(0x2A, 2, {i: bytes([2040 & 0xFF, 2040 >> 8]) for i in range(1, 9)}),
        "t0: SYNC_WRITE pos=2040 (per=2, 32B)")

    # 2. 轮询回读 #1（无负载）
    req(sp.build_read(1, 0x3A, 8), "t1: READ servo#1 feedback (no load)")

    # 3. 轮询回读 #2（注入负载 500 → 响应含 load）
    bus.inject_external_load({2: 500})
    req(sp.build_read(2, 0x3A, 8), "t2: READ servo#2 feedback (load=500)")

    # 4. 事件帧：广播速度 3
    req(sp.build_write(sp.BROADCAST_ID, 0x2E, bytes([3])), "evt: BC write speed=3")

    # 5. 掉线：舵机 3 静默 → READ #3 无响应
    bus.inject_drop([3])
    req(sp.build_read(3, 0x3A, 8), "t3: READ servo#3 (dropped -> no S lines)")

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    n_m = sum(1 for l in lines if l.startswith("M "))
    n_s = sum(1 for l in lines if l.startswith("S "))
    print(f"golden vectors -> {OUT} ({n_m} M-bytes, {n_s} S-bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
